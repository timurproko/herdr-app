// Plugins: one folder each under src/plugins/<id>/, entry plugin.js. The build packages
// every plugin, the plugin API and the registry into each mod that uses plugins, so a
// new plugin is just a new folder: no manifest lines, no registry edits.
import fs from 'node:fs';
import path from 'node:path';
import {gzipSync} from 'node:zlib';
import {safeRelative} from './files.mjs';

export const PLUGIN_SOURCE = 'src/plugins';
const ID = /^[a-z0-9][a-z0-9-]{0,62}$/;
// Shipped beside the plugins in every plugin mod (packaged path -> source).
const SHARED = Object.freeze({ 'plugins.js': `${PLUGIN_SOURCE}/registry.js`, 'plugins/api.js': `${PLUGIN_SOURCE}/api.js`, 'plugins/api.cjs': `${PLUGIN_SOURCE}/api.cjs`, 'fleet-display.js': 'src/shared/fleet-display.js' });
const isTest = name => /\.test\.[cm]?js$/.test(name);

function walk(dir, base = '') {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => {
    const rel = base + e.name;
    if (e.isSymbolicLink()) throw Error(`Refusing linked plugin file: ${rel}`);
    return e.isDirectory() ? walk(path.join(dir, e.name), rel + '/') : [rel];
  });
}

// { ids (load order), mods, files: [{ rel, source }] } — rel is relative to a mod folder.
export function pluginLayout(root, config) {
  const dir = path.join(root, PLUGIN_SOURCE);
  const found = fs.readdirSync(dir, { withFileTypes: true })
    .filter(e => e.isDirectory() && fs.existsSync(path.join(dir, e.name, 'plugin.js'))).map(e => e.name).sort();
  for (const id of found) if (!ID.test(id)) throw Error(`Invalid plugin folder name: ${id}`);
  // Order decides hook priority and the order on the Plugins page; unlisted plugins follow alphabetically.
  const order = config.plugins?.order ?? [];
  for (const id of order) if (!found.includes(id)) throw Error(`Plugin listed in customization.json but has no folder: ${id}`);
  const ids = [...order, ...found.filter(id => !order.includes(id))];
  const mods = config.plugins?.mods ?? [];
  for (const mod of mods) if (!config.features.some(f => f.mod === mod)) throw Error(`Plugin mod is not a feature mod: ${mod}`);
  const files = Object.entries(SHARED).map(([rel, source]) => ({ rel, source }));
  const modFiles = [], settingsPages = [], owners = new Set();
  for (const id of ids) {
    // Panel implementations live only in their own sandbox, never in another
    // plugin's mod. Other consumers load the lightweight declaration alone.
    for (const rel of walk(path.join(dir, id)))
      if (!isTest(rel) && !rel.startsWith('mod/') && rel !== 'panel.json') files.push({ rel: `plugins/${id}/${rel}`, source: `${PLUGIN_SOURCE}/${id}/${rel}` });
    const manifest = path.join(dir, id, 'panel.json');
    if (!fs.existsSync(manifest)) continue;
    const panel = JSON.parse(fs.readFileSync(manifest, 'utf8'));
    if (!config.features.some(f => f.mod === panel.mod) || !mods.includes(panel.mod) || owners.has(panel.mod)) throw Error(`Invalid plugin panel owner: ${id}`);
    owners.add(panel.mod);
    for (const rel of walk(path.join(dir, id, 'mod')).filter(rel => !isTest(rel)))
      modFiles.push({dest:`mods/${panel.mod}/${rel}`,source:`${PLUGIN_SOURCE}/${id}/mod/${rel}`});
    for (const [rel, source] of Object.entries(panel.shared ?? {})) {
      safeRelative(rel); safeRelative(source);
      if (!source.startsWith('src/') || source.startsWith(`${PLUGIN_SOURCE}/`) && !source.startsWith(`${PLUGIN_SOURCE}/${id}/`)) throw Error(`Panel ${id} may not depend on a peer plugin: ${source}`);
      modFiles.push({dest:`mods/${panel.mod}/${rel}`,source});
    }
    for(const [target,entries] of Object.entries(panel.extensions ?? {})) {
      if(!mods.includes(target) || !config.features.some(f=>f.mod===target)) throw Error(`Invalid plugin extension target: ${target}`);
      for(const [rel,source] of Object.entries(entries)) {
        safeRelative(rel);safeRelative(source);
        modFiles.push({dest:`mods/${target}/${rel}`,source:`${PLUGIN_SOURCE}/${id}/${source}`});
      }
    }
    if(panel.settingsPage) {
      const page=panel.settingsPage;
      if(!mods.includes(page.mod) || !ID.test(page.section) || !/^[A-Za-z][A-Za-z0-9]*$/.test(page.export)) throw Error(`Invalid plugin settings page: ${id}`);
      safeRelative(page.entry);
      if(!modFiles.some(f=>f.dest===`mods/${page.mod}/${page.entry}`)) throw Error(`Unpackaged settings page: ${id}`);
      settingsPages.push({...page,plugin:id});
    }
  }
  return { ids, mods, files, modFiles, settingsPages };
}

// Generated per mod: which plugins exist, and which mod this copy lives in.
export const indexSource = ids => '// Generated by tools/plugins.mjs from the folders in src/plugins/.\n'
  + ids.map((id, i) => `import p${i} from './${id}/plugin.js';`).join('\n')
  + `\nexport default [${ids.map((_, i) => `p${i}`).join(', ')}];\n`;
export const whereSource = mod => `// Generated by tools/plugins.mjs.\nexport const MOD = ${JSON.stringify(mod)};\n`;

// Explicit Node workers may use ../api.cjs, the shared A1 adapter. Bundle it once
// into each transported worker, so node -e on a Core-only host needs no files.
function workerBytes(root, source) {
  const api=fs.readFileSync(path.join(root,PLUGIN_SOURCE,'api.cjs'),'utf8');
  const worker=fs.readFileSync(path.join(root,source),'utf8');
  const bundled=`const api=(()=>{const module={exports:{}};(function(module,exports,require){\n${api}\n})(module,module.exports,require);return module.exports;})();\n(function(module,exports,require){\n${worker}\n})(module,module.exports,Object.assign(name=>name==='../api.cjs'?api:require(name),require));\n`;
  const encoded=gzipSync(Buffer.from(bundled),{level:9,mtime:0}).toString('base64');
  return Buffer.from(`// Generated self-contained plugin worker.\neval(require('node:zlib').gunzipSync(Buffer.from('${encoded}','base64')).toString('utf8'));\n`);
}

// Every packaged plugin file for every plugin mod: [{ dest, source, bytes }].
export function pluginEntries(root, config) {
  const { ids, mods, files, modFiles, settingsPages } = pluginLayout(root, config), out = modFiles.map(file => ({...file,bytes:fs.readFileSync(path.join(root,file.source))}));
  const workers=new Set((config.plugins?.nodeWorkers??[]).map(name=>`plugins/${name}`));
  for(const worker of workers) if(!files.some(file=>file.rel===worker) || !worker.endsWith('.cjs')) throw Error(`Unknown plugin Node worker: ${worker}`);
  for (const mod of mods) {
    for (const { rel, source } of files) out.push({ dest: `mods/${mod}/${rel}`, source, bytes: workers.has(rel)?workerBytes(root,source):fs.readFileSync(path.join(root, source)) });
    const pages=settingsPages.filter(p=>p.mod===mod);
    if(pages.length) {
      const imports=pages.map((p,i)=>`import {${p.export} as page${i}} from './${p.entry}';`).join('\n');
      // A page is a declaration (docs/PLUGIN-UI.md); the shared renderer draws it.
      const entries=pages.map((p,i)=>`${JSON.stringify(p.section)}:{plugin:${JSON.stringify(p.plugin)},page:page${i}}`).join(',');
      const source=`import {pluginIsEnabled} from './plugins.js';\nimport {pluginPage} from './plugins-ui.js';\n${imports}\nconst pages={${entries}};\nexport function renderPluginSettings(section,owner,theme){const page=pages[section];return page&&pluginIsEnabled(page.plugin)?pluginPage(owner,theme,page.page):null;}\nexport function pluginPageRefresh(section){const page=pages[section];return page&&pluginIsEnabled(page.plugin)&&page.page.machine?page.page.refresh??null:null;}\n`;
      out.push({dest:`mods/${mod}/plugin-pages.js`,source:'generated',bytes:Buffer.from(source)});
    }
    out.push({ dest: `mods/${mod}/plugins/index.js`, source: 'tools/plugins.mjs', bytes: Buffer.from(indexSource(ids)) });
    out.push({ dest: `mods/${mod}/plugins/where.js`, source: 'tools/plugins.mjs', bytes: Buffer.from(whereSource(mod)) });
  }
  return out;
}

// Plugin tests live in their plugin's folder.
export function pluginTests(root) {
  const dir = path.join(root, PLUGIN_SOURCE);
  return fs.readdirSync(dir, { withFileTypes: true }).filter(e => e.isDirectory())
    .flatMap(e => walk(path.join(dir, e.name)).filter(isTest).map(rel => `${PLUGIN_SOURCE}/${e.name}/${rel}`)).sort();
}
