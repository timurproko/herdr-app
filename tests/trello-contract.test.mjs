import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {routes}=require('../src/plugins/trello/client.cjs');
const {definitions,writes}=require('../src/plugins/trello/operations.cjs');
const guide=fs.readFileSync(new URL('../docs/TRELLO.md',import.meta.url),'utf8');
const readme=fs.readFileSync(new URL('../README.md',import.meta.url),'utf8');
assert.ok(readme.includes('docs/TRELLO.md'));
for(const term of ['trello.com/apps/admin','response_type=token','scope=read,write','Revoke','same OS user','read the credential file','allowlist','UNKNOWN_WRITE','HERDR_TRELLO_BIN','not MCP','API key','user token','OAuth 2.0','private plaintext'])assert.ok(guide.includes(term),term);
for(const op of ['boards.list','lists.list','cards.list','cards.get','labels.list','checklists.list','checkitems.list'])assert.ok(definitions[op]);
assert.equal(writes.size,11);
assert.equal(routes.filter(([m])=>m==='DELETE').length,1);
assert.ok(routes.find(([m])=>m==='DELETE')[1].source.includes('idLabels'));
for(const keys of Object.values(definitions))for(const excluded of ['url','method','token','apiKey','idCardSource','idChecklistSource','fileSource','urlSource'])assert.ok(!keys.includes(excluded));
for(const op of ['cards.delete','checklists.delete','checkitems.delete','labels.create','boards.create','request'])assert.ok(!definitions[op]);
const config=JSON.parse(fs.readFileSync(new URL('../customization.json',import.meta.url)));
assert.equal(config.files['lib/trello/cli.cjs'],'src/plugins/trello/cli.cjs');
assert.ok(!Object.keys(config.files).some(k=>/trello\/(?:credentials|policy|cooldown)\.json$/.test(k)));
assert.ok(guide.includes('No real-board or real-token'));
console.log('PASS: Trello owner guidance, official token/revocation references, finite operation catalog and non-payload private stores');
